import fs from "node:fs";
import ts from "typescript";

const walk = (directory) => fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
  entry.isDirectory() ? walk(`${directory}/${entry.name}`) : entry.name.endsWith(".tsx") && !entry.name.includes(".test.") ? [`${directory}/${entry.name}`] : [],
);
const files = [...walk("app"), ...walk("components")].filter((file) => (!file.startsWith("app/api/") || file === "app/api/og/route.tsx")).sort();
const controlTags = new Set(["button", "input", "select", "textarea", "a", "Link", "summary", "dialog"]);
const activationHandler = /^on(?:Click|DoubleClick|KeyDown|KeyUp|PointerDown|PointerUp|Submit)$/;
const escape = (text) => text.replaceAll("|", "\\|").replaceAll("\n", " ").replaceAll("`", "'").replace(/\s+/g, " ").trim();
const inventory = files.map((file) => {
  const source = ts.createSourceFile(file, fs.readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const controls = [];
  const components = new Set();
  const classes = new Set();
  const visit = (node) => {
    if (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) {
      const tag = node.tagName.getText(source);
      if (/^[A-Z]/.test(tag)) components.add(tag);
      const attributes = node.attributes.properties.filter(ts.isJsxAttribute);
      const attr = (name) => attributes.find((attribute) => attribute.name.getText(source) === name)?.initializer?.getText(source) || "";
      if (attr("className")) classes.add(escape(attr("className")));
      if (controlTags.has(tag) || attributes.some((attribute) => activationHandler.test(attribute.name.getText(source)))) controls.push({
        line: source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1,
        tag,
        identity: escape(attr("aria-label") || attr("id") || attr("name") || attr("href") || attr("className") || tag),
        behavior: attributes.filter((attribute) => /^(on[A-Z]|type|disabled|required|aria-|role)/.test(attribute.name.getText(source))).map((attribute) => attribute.name.getText(source)).join(", "),
        styling: escape(attr("className")) || "Native control system",
      });
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return { file, controls, components: [...components], classes: [...classes] };
});
const total = inventory.reduce((sum, file) => sum + file.controls.length, 0);
const routes = inventory.filter(({ file }) => file.startsWith("app/") && file.endsWith("/page.tsx"));
const lines = [
  "# Chronicle frontend inventory", "",
  "Generated by `node scripts/mapFrontend.mjs`. Source-level inventory: repeated controls created by loops are recorded once, with their original expressions. It is not a claim of browser verification.", "",
  `**${routes.length} page entry points · ${inventory.filter(({ file }) => file.startsWith("components/")).length} shared component files · ${total} control and activation definitions.**`, "",
  "## Scope and visual ownership", "",
  "- The web interface uses Paper & Lilac and Dusk & Lilac. Anime.js drives short entrances and drawn accents acknowledge saved progress.",
  "- Preserve: real server authentication, account scope, exact manual progress, tracker/notification contracts, file upload protocol, saved reader preferences and original content.",
  "- Exclusions: no backend/schema changes, deployment, commits, push, Android native changes, or changes to unrelated documentation.",
  "- `app/sakuga.css` defines shared surfaces, controls, and interaction states. `app/themes.css` supplies the dark palette and theme change. The landing and Home CSS modules own their page layouts. Earlier styles retain structural feature layouts. `components/motion/SakugaEffects.tsx` enhances visible sections and portals.",
  "- Motion: one bounded canvas for successful saves, observed state changes, no idle render loop; native controls retain keyboard, forms and labels. System reduced motion overrides the device preference. Reader text never triggers impact effects.",
  "- Proof: see `docs/FRONTEND_REDESIGN.md` for the route/state verification matrix and explicit limitations.", "",
  "## Pages", "", "| Entry point | Direct controls | Composed components |", "| --- | ---: | --- |",
  ...routes.map(({ file, controls, components }) => `| ${file} | ${controls.length} | ${components.join(", ")} |`), "",
  "## Every component and control", "",
];
for (const { file, controls, components, classes } of inventory) {
  lines.push(`### ${file}`, "", `Composes: ${components.join(", ") || "native markup"}.`, "");
  if (controls.length) {
    lines.push("| Line | Control | Identity | Behavior/state attributes | Visual hook |", "| ---: | --- | --- | --- | --- |");
    for (const control of controls) lines.push(`| ${control.line} | ${control.tag} | ${control.identity} | ${control.behavior || "native navigation/activation"} | ${control.styling} |`);
    lines.push("");
  } else lines.push("No direct controls; visual surface or composed page.", "");
  lines.push("Surface hooks: " + (classes.map((item) => `\`${item}\``).join(", ") || "Inherited from composed components") + ".", "");
}
fs.writeFileSync("docs/FRONTEND_INVENTORY.md", lines.join("\n"));
console.log(`Mapped ${routes.length} pages, ${inventory.length} source files, ${total} control definitions.`);
